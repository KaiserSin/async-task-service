-- Initial schema. Flyway applies each migration once, in version order, and records it in flyway_schema_history.
-- Never edit an applied migration: add the next version (V2__..., V3__...) instead.

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    owner_username VARCHAR(255) NOT NULL,
    payment_operation_id UUID NOT NULL UNIQUE,
    order_id UUID NOT NULL,
    amount BIGINT NOT NULL CHECK (amount BETWEEN 1 AND 99999999),
    currency VARCHAR(3) NOT NULL CHECK (currency ~ '^[a-z]{3}$'),
    payment_method_id VARCHAR(255) NOT NULL CHECK (payment_method_id ~ '^pm_[A-Za-z0-9_]+$'),
    idempotency_key VARCHAR(255) NOT NULL UNIQUE,
    provider_payment_id VARCHAR(255) UNIQUE,
    payment_status VARCHAR(32) NOT NULL DEFAULT 'NOT_SUBMITTED',
    execution_status VARCHAR(20) NOT NULL DEFAULT 'NEW'
        CHECK (execution_status IN ('NEW', 'IN_PROGRESS', 'COMPLETED', 'FAILED')),
    result TEXT,
    execution_id UUID,
    lease_until TIMESTAMPTZ,
    next_retry_at TIMESTAMPTZ,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts INTEGER NOT NULL DEFAULT 3 CHECK (max_attempts > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    worker_attempted BOOLEAN NOT NULL DEFAULT FALSE,
    replacement_payment_method_id VARCHAR(255),
    pending_confirmation_key VARCHAR(255),
    action_expires_at TIMESTAMPTZ,
    abandonment_started BOOLEAN NOT NULL DEFAULT FALSE,
    next_status_check_at TIMESTAMPTZ,
    processing_since TIMESTAMPTZ,
    first_terminal_at TIMESTAMPTZ,
    CONSTRAINT payments_running_state CHECK (
        execution_status <> 'IN_PROGRESS'
        OR (execution_id IS NOT NULL AND started_at IS NOT NULL)
    ),
    CONSTRAINT payments_finished_state CHECK (
        execution_status NOT IN ('COMPLETED', 'FAILED') OR finished_at IS NOT NULL
    )
);

-- Worker results, webhooks and reconciliation all use the same deadline.
CREATE FUNCTION schedule_payment_status_check() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.first_terminal_at IS NULL AND OLD.payment_status NOT IN ('SUCCEEDED', 'CANCELED')
            AND NEW.payment_status IN ('SUCCEEDED', 'CANCELED') THEN
        NEW.first_terminal_at := clock_timestamp();
    END IF;
    NEW.processing_since := CASE WHEN NEW.payment_status = 'PROCESSING'
        THEN COALESCE(OLD.processing_since, statement_timestamp()) END;
    IF NEW.abandonment_started AND NEW.payment_status NOT IN ('SUCCEEDED', 'CANCELED') THEN
        NEW.next_status_check_at := statement_timestamp() + INTERVAL '15 minutes';
    ELSIF NEW.payment_status = 'REQUIRES_ACTION' THEN
        NEW.action_expires_at := COALESCE(NEW.action_expires_at, statement_timestamp() + INTERVAL '15 minutes');
        NEW.next_status_check_at := NEW.action_expires_at;
    ELSIF NEW.payment_status IN ('PROCESSING', 'AWAITING_WEBHOOK') THEN
        NEW.next_status_check_at := statement_timestamp() + INTERVAL '15 minutes';
    ELSE
        NEW.next_status_check_at := NULL;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER payment_status_check_schedule
    BEFORE UPDATE OF payment_status ON payments FOR EACH ROW
    WHEN (OLD.payment_status IS DISTINCT FROM NEW.payment_status)
    EXECUTE FUNCTION schedule_payment_status_check();

CREATE TABLE archived_payments (
    payment_operation_id UUID PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    payment_id BIGINT NOT NULL,
    order_id UUID NOT NULL,
    owner_username VARCHAR(255) NOT NULL,
    amount BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL,
    payment_method_id VARCHAR(255) NOT NULL,
    replacement_payment_method_id VARCHAR(255),
    provider_payment_id VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ,
    archived_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_status VARCHAR(32) NOT NULL
);

CREATE TABLE payment_registration_events (
    event_id UUID PRIMARY KEY,
    payment_operation_id UUID NOT NULL
);

CREATE TABLE stripe_webhook_events (
    event_id TEXT PRIMARY KEY,
    event_type TEXT NOT NULL,
    payload TEXT,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ,
    -- The event is hidden from processors until available_at, both while claimed and during retry backoff.
    available_at TIMESTAMPTZ,
    review_reason TEXT CONSTRAINT webhook_review_reason_known CHECK (review_reason IN
        ('MISSING_OPERATION_ID', 'INVALID_OPERATION_ID', 'OPERATION_MISMATCH', 'INTENT_MISMATCH',
         'AMOUNT_MISMATCH', 'ORDER_MISMATCH', 'CURRENCY_MISMATCH', 'TECHNICAL_ERROR')),
    technical_failures INTEGER NOT NULL DEFAULT 0 CHECK (technical_failures BETWEEN 0 AND 3)
);

CREATE TABLE shedlock (
    name VARCHAR(64) NOT NULL PRIMARY KEY,
    lock_until TIMESTAMP NOT NULL,
    locked_at TIMESTAMP NOT NULL,
    locked_by VARCHAR(255) NOT NULL
);

CREATE INDEX idx_payments_first_terminal_at ON payments (first_terminal_at)
    WHERE first_terminal_at IS NOT NULL;
CREATE INDEX idx_payments_processing_since ON payments (processing_since, id)
    WHERE payment_status = 'PROCESSING';
CREATE INDEX idx_payments_pending_status_check ON payments (next_status_check_at, id)
    WHERE execution_status IN ('COMPLETED', 'FAILED') AND next_status_check_at IS NOT NULL;
CREATE INDEX idx_payments_owner_created_at ON payments (owner_username, created_at);
CREATE INDEX idx_payments_new_id ON payments (id) WHERE execution_status = 'NEW';
CREATE INDEX idx_payments_status_finished_at_id ON payments (execution_status, finished_at, id);
CREATE INDEX idx_payments_failed_unknown_finished_at ON payments (finished_at)
    WHERE execution_status = 'FAILED' AND payment_status = 'UNKNOWN';
CREATE INDEX idx_stripe_webhook_events_processed
    ON stripe_webhook_events (processed_at, event_id) WHERE processed_at IS NOT NULL;
CREATE INDEX idx_stripe_webhook_events_ready
    ON stripe_webhook_events (received_at, event_id) WHERE processed_at IS NULL AND review_reason IS NULL;
CREATE INDEX idx_archived_payments_provider_id ON archived_payments (provider_payment_id);
